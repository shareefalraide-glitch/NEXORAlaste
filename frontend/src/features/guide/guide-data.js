const allowed = new Set(guideSteps.map(step => step.id));
export const initialGuide = () => {
  const fallback = { version: 2, visible: true, visited: [], lastStep: null, finished: false };
  try {
    const value = JSON.parse(localStorage.getItem('nexora-ui-guide') || 'null');
    // The older three-link guide is a different experience, so offer the new tour.
    if (!value || value.version !== 2) return fallback;
    const visited = Array.isArray(value.visited)
      ? [...new Set(value.visited.filter(id => allowed.has(id)))]
      : [];
    return {
      ...fallback,
      visible: value.visible !== false,
      visited,
      lastStep: allowed.has(value.lastStep) ? value.lastStep : null,
      finished: value.finished === true,
    };
  } catch {
    return fallback;
  }
};
